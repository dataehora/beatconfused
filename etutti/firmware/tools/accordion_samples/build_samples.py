"""Turns the recordings in capturas/ into looped reed samples for the firmware.

For each reed rank (L, M, M2, H) and each recorded note it keeps the real
start of the note, cross-fades it into a steady stretch, and loops a whole
number of periods of that stretch. It writes

  ../../student_v4/reed_samples.cpp + .h   the sample data (not tracked by
                                             git: it is made from a licensed
                                             library and stays on this PC)
  capturas/preview/<rank>_<key>.wav          each sample played for 4 s, to
                                             listen for loop clicks or wobble

Run with a Python that has numpy and scipy:  python build_samples.py
"""
import os
from math import gcd

import numpy as np
from scipy.io import wavfile
from scipy.signal import resample_poly

from analyse import load, find_notes, fundamental
from make_capture_midi import NOTES, SOUNDING_OFFSET

HERE = os.path.dirname(os.path.abspath(__file__))
SKETCH = os.path.normpath(os.path.join(HERE, "..", "..", "student_v4"))
PREVIEW = os.path.join(HERE, "capturas", "preview")

# rank -> (octave of its pitch relative to the 8' reeds, stored sample rate).
# The 4' rank reaches 3 kHz fundamentals, so it keeps a higher rate.
RANKS = {"L": (-1, 24000), "M": (0, 24000), "M2": (0, 24000), "H": (1, 32000)}
ATTACK_S = 0.10       # of the real note start kept
SPLICE_S = 0.020      # cross-fade from the start into the steady stretch
STEADY_FROM_S = 1.0   # where the steady stretch may begin
LOOP_S = (0.25, 0.40) # allowed loop length
LOOP_FADE_S = 0.025   # cross-fade that closes the loop
START_MAX = 1.0      # loudest the start may be, relative to the loop level
TARGET_RMS = 0.18     # loop level of every sample, full scale = 1
GUARD = 3             # samples repeated after the loop end for interpolation


def rms(x):
    return float(np.sqrt(np.mean(x * x)))


def build_one(x, rate, f0):
    """x: one note from just before its onset. Returns (data, loop_start, report)."""
    period = rate / f0
    fade = int(LOOP_FADE_S * rate)
    splice = int(SPLICE_S * rate)

    # loop length: the whole number of periods closest to a whole number of samples
    best = None
    for k in range(int(LOOP_S[0] * rate / period), int(LOOP_S[1] * rate / period) + 1):
        err = abs(k * period - round(k * period))
        if best is None or err < best[0]:
            best = (err, int(round(k * period)))
    length = best[1]

    # loop start: where the stretch before it best matches the loop's last samples
    first = int(STEADY_FROM_S * rate)
    last = min(len(x) - length - 1, first + int(0.8 * rate))
    best = None
    for s in range(first, last, max(1, int(period / 8))):
        a, b = x[s - fade:s], x[s + length - fade:s + length]
        err = rms(a - b) / (rms(a) + 1e-12)
        if best is None or err < best[0]:
            best = (err, s)
    loop_err, s = best

    body = x[s:s + length].copy()
    w = np.linspace(0.0, 1.0, fade, endpoint=False)
    body[length - fade:] = body[length - fade:] * (1 - w) + x[s - fade:s] * w

    # the real start, joined in phase with the samples just before the loop
    target = x[s - splice:s]
    a0 = int(ATTACK_S * rate)
    best = None
    for a in range(a0, a0 + int(period) + 1):
        c = float(np.dot(x[a:a + splice], target))
        if best is None or c > best[0]:
            best = (c, a)
    a = best[1]
    gain = float(np.clip(rms(target) / (rms(x[a:a + splice]) + 1e-12), 0.5, 3.0))
    w = np.linspace(0.0, 1.0, splice, endpoint=False)
    join = x[a:a + splice] * gain * (1 - w) + target * w
    data = np.concatenate([x[:a] * gain, join, body])
    loop_start = a + splice

    # The start must not be louder than the held note: where the level before
    # the loop rises above the loop's own, it is turned down to it. (Matching
    # the join's level can push an earlier, already loud moment well above it.)
    win = max(1, int(0.008 * rate))
    env = np.sqrt(np.convolve(data[:loop_start + win] ** 2, np.ones(win) / win, mode="same"))[:loop_start]
    trim = np.minimum(1.0, START_MAX * rms(body) / (env + 1e-12))
    trim = np.convolve(np.pad(trim, win, mode="edge"), np.ones(win) / win, mode="same")[win:-win]
    data[:loop_start] *= trim

    scale = TARGET_RMS / rms(body)
    data = data * scale
    peak = float(np.abs(data).max())
    if peak > 0.98:
        data *= 0.98 / peak
    data = np.concatenate([data, data[loop_start:loop_start + GUARD]])
    return data, loop_start, dict(loop_err=loop_err, length=length, gain=gain, trim=float(trim.min()), peak=min(peak, 0.98))


def main():
    os.makedirs(PREVIEW, exist_ok=True)
    cpp = ['// Generated by tools/accordion_samples/build_samples.py. Do not edit, do not publish.',
           '#include "reed_sampler.h"', '']
    rows = []
    total = 0
    for rank, (octave, rate) in RANKS.items():
        src_rate, x = load(rank)
        notes, _ = find_notes(x, src_rate)
        assert len(notes) == len(NOTES), f"{rank}: {len(notes)} notes found, {len(NOTES)} expected"
        g = gcd(rate, src_rate)
        entries = []
        for i, (a, b) in enumerate(notes):
            key = NOTES[i] + SOUNDING_OFFSET + 12 * octave      # sounding MIDI note
            guess = 440.0 * 2 ** ((key - 69) / 12.0)
            f0, _ = fundamental(x[a + src_rate:a + int(2.5 * src_rate)], src_rate, guess)
            seg = x[max(0, a - int(0.005 * src_rate)):b]
            seg = resample_poly(seg, rate // g, src_rate // g)
            data, loop_start, rep = build_one(seg, rate, f0)
            root = 69 + 12 * np.log2(f0 / 440.0)
            n_loop_end = len(data) - GUARD
            name = f"reed_{rank}_{i}"
            ints = np.round(data * 32767).astype(np.int16)
            cpp.append(f"static const int16_t {name}[{len(ints)}] PROGMEM = {{")
            for j in range(0, len(ints), 16):
                cpp.append(",".join(str(v) for v in ints[j:j + 16]) + ",")
            cpp.append("};")
            entries.append(f"  {{ {name}, {n_loop_end}, {loop_start}, {root:.4f}f, {rate}.0f }},")
            total += ints.nbytes
            print(f"{rank:2} key {key:3} f0 {f0:8.2f} len {len(ints):6} loop {rep['length']:5} "
                  f"err {rep['loop_err']:.3f} attack gain {rep['gain']:.2f} trim {rep['trim']:.2f} peak {rep['peak']:.2f}")
            # preview: the start, then the loop repeated up to 4 s
            reps = int(4.0 * rate / rep["length"]) + 1
            play = np.concatenate([data[:loop_start]] + [data[loop_start:n_loop_end]] * reps)
            wavfile.write(os.path.join(PREVIEW, f"{rank}_{key}.wav"), rate,
                          np.round(play * 32767).astype(np.int16))
        rows.append((rank, entries))
    cpp.append("")
    cpp.append(f"const ReedSample reedSamples[REED_RANKS][REED_SAMPLES_PER_RANK] = {{")
    for rank, entries in rows:
        cpp.append(f"  {{ // {rank}")
        cpp.extend("  " + e for e in entries)
        cpp.append("  },")
    cpp.append("};")
    with open(os.path.join(SKETCH, "reed_samples.cpp"), "w", newline="\n") as f:
        f.write("\n".join(cpp) + "\n")
    with open(os.path.join(SKETCH, "reed_samples.h"), "w", newline="\n") as f:
        f.write("// Generated by tools/accordion_samples/build_samples.py.\n"
                "// Its presence switches the accordion from synthesised to sampled reeds.\n"
                "#pragma once\n"
                f"#define REED_SAMPLES_PER_RANK {len(NOTES)}\n")
    print(f"total {total / 1024:.0f} KB of sample data")


if __name__ == "__main__":
    main()
