"""Impedance of the USB pair (C1) on the Viaggio's stack-up, by a 2D field solver.

    "C:/Users/julia/.venvs/cadquery/Scripts/python.exe" etutti/hardware/viaggio_micromod/pcb/impedance.py

Needs numpy + scipy (the CadQuery venv has both). Writes build/impedance.json,
which build_board.py reads for the USB rule and ELETRONICA.md quotes.

Stack-up: JLCPCB JLC04121H-7628 (4 layers, 1.2 mm, outer 1 oz, inner 0.5 oz),
as published by JLCPCB's impedance-template API (copied in STACKUP below,
source: github.com/gsuberland/jlcpcb_autogenerated_stackups, normalised_json/
jlcpcb_4L_1.2mm_outer1oz_inner0.5oz_JLC04121H-7628.json):
  F.Cu 0.035 | 7628 prepreg 0.2104 (Dk 4.4) | In1 0.0152 | core 0.6 (Dk 4.36)
  | In2 0.0152 | 7628 prepreg 0.2104 (Dk 4.4) | B.Cu 0.035
The USB pair runs on F.Cu over the In1 GND plane: an edge-coupled surface
microstrip, h = 0.2104 mm, t = 0.035 mm, with ~15 um of solder mask (Dk 3.8).

Method: finite differences on 5 and 2.5 um grids (Richardson-extrapolated) (Laplace with the dielectric
interfaces), ground plane and a far box at 0 V. C (with dielectrics) and C0
(all air) per unit length from the field energy; Z = 1 / (c0 sqrt(C C0)).
Odd mode (+1 / -1 V) gives Zdiff = 2 Z_odd. Checked against the closed-form
IPC-2141A estimate and the one JLCPCB calculator figure found for a 7628 4-layer
board (85 ohm at w 8.09 mil / gap 4 mil).
"""
import json
import math
import os

import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spl

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "build", "impedance.json")

STACKUP_NAME = "JLC04121H-7628"
STACKUP = [  # (name, kind, thickness mm, Dk)
    ("F.Cu", "copper", 0.035, None),
    ("prepreg 7628", "prepreg", 0.2104, 4.4),
    ("In1.Cu", "copper", 0.0152, None),
    ("core", "core", 0.6, 4.36),
    ("In2.Cu", "copper", 0.0152, None),
    ("prepreg 7628", "prepreg", 0.2104, 4.4),
    ("B.Cu", "copper", 0.035, None),
]
H, T, ER, MASK_T, MASK_ER = 0.2104, 0.035, 4.4, 0.015, 3.8
C0 = 299792458.0
EPS0 = 8.854187817e-12


def solve(w, s, er_on=True, pair=True, d=0.01, width=6.0, height=2.0):
    nx, ny = int(width / d), int(height / d)
    x = (np.arange(nx) - nx / 2 + 0.5) * d
    y = (np.arange(ny) + 0.5) * d                  # y = 0 is the ground plane's top
    X, Y = np.meshgrid(x, y)
    er = np.ones((ny, nx))
    if er_on:
        er[Y < H] = ER
    xs = [(-s / 2 - w, -s / 2), (s / 2, s / 2 + w)] if pair else [(-w / 2, w / 2)]
    volt = [1.0, -1.0] if pair else [1.0]
    cond = np.zeros((ny, nx), bool)
    val = np.zeros((ny, nx))
    for (a, b), v in zip(xs, volt):
        m = (X >= a) & (X <= b) & (Y >= H) & (Y <= H + T)
        cond |= m
        val[m] = v
    if er_on:                                       # solder mask: on the substrate and over the traces
        mask = (Y >= H) & (Y < H + MASK_T) & ~cond
        for a, b in xs:
            mask |= (X >= a - MASK_T) & (X <= b + MASK_T) & (Y >= H) & (Y < H + T + MASK_T) & ~cond
        er[mask] = MASK_ER
    # unknowns: every cell not a conductor; boundaries (box) at 0 V
    idx = -np.ones((ny, nx), int)
    free = ~cond
    idx[free] = np.arange(free.sum())
    n = int(free.sum())
    rows, cols, data = [], [], []
    rhs = np.zeros(n)
    # edge permittivity between neighbours = harmonic-ish mean (series): use arithmetic mean of the two cells
    for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
        nb_y = np.arange(ny)[:, None] + dy
        nb_x = np.arange(nx)[None, :] + dx
        nb_y = np.broadcast_to(nb_y, (ny, nx))
        nb_x = np.broadcast_to(nb_x, (ny, nx))
        inside = (nb_y >= 0) & (nb_y < ny) & (nb_x >= 0) & (nb_x < nx)
        nyc, nxc = np.clip(nb_y, 0, ny - 1), np.clip(nb_x, 0, nx - 1)
        e = np.where(inside, 0.5 * (er + er[nyc, nxc]), er)
        me = free
        i_me = idx[me]
        e_me = e[me]
        rows.append(i_me)
        cols.append(i_me)
        data.append(e_me)                            # diagonal
        nb_in = inside[me]
        nb_free = nb_in & free[nyc, nxc][me]
        rows.append(i_me[nb_free])
        cols.append(idx[nyc, nxc][me][nb_free])
        data.append(-e_me[nb_free])
        nb_cond = nb_in & cond[nyc, nxc][me]
        np.add.at(rhs, i_me[nb_cond], e_me[nb_cond] * val[nyc, nxc][me][nb_cond])
        # out of the box (and y < 0, the ground plane) = 0 V: nothing to add
    A = sp.csr_matrix((np.concatenate(data), (np.concatenate(rows), np.concatenate(cols))), shape=(n, n))
    phi = np.zeros((ny, nx))
    phi[free] = spl.spsolve(A, rhs)
    phi[cond] = val[cond]
    # energy per unit length: 1/2 eps0 sum er |grad phi|^2 (cells of d x d; d in m)
    p = np.pad(phi, 1)                              # 0 V outside, ground plane below
    gx = (p[1:-1, 2:] - p[1:-1, :-2]) / 2
    gy = (p[2:, 1:-1] - p[:-2, 1:-1]) / 2
    W = 0.5 * EPS0 * np.sum(er * (gx ** 2 + gy ** 2))   # per metre (d cancels: grad per cell * cell area)
    return W * (2 if not pair else 1)               # C = 2W/V^2 single; odd mode C_line = W (two lines at +/-1)


def z(w, s=None):
    """(Z, sqrt(eps_eff)); Z single-ended, or Z_odd for a pair. The finite-difference error is
    first order in the grid step here (conductor edges and the plane fall half a cell off), so the
    result is Richardson-extrapolated from 5 um and 2.5 um grids (3 x 1 mm box)."""
    pair = s is not None
    out = []
    for d in (0.005, 0.0025):
        C = solve(w, s or 0.0, True, pair, d, 3.0, 1.0)
        Ca = solve(w, s or 0.0, False, pair, d, 3.0, 1.0)
        out.append((1.0 / (C0 * math.sqrt(C * Ca)), math.sqrt(C / Ca)))
    return 2 * out[1][0] - out[0][0], out[1][1]


def ipc2141(w, s):
    z0 = 87 / math.sqrt(ER + 1.41) * math.log(5.98 * H / (0.8 * w + T))
    return 2 * z0 * (1 - 0.48 * math.exp(-0.96 * s / H))


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    z50, _ = z(0.37)
    jlc85, _ = z(8.09 * 0.0254, 4 * 0.0254)
    table = []
    for w in (0.20, 0.22, 0.24, 0.26):
        for s in (0.127, 0.15):
            zo, ee = z(w, s)
            table.append({"w": w, "s": s, "zdiff": round(2 * zo, 1), "eeff": round(ee ** 2, 2),
                          "ipc2141": round(ipc2141(w, s), 1)})
            print("w %.3f s %.3f  Zdiff %.1f  (IPC-2141A %.1f)" % (w, s, 2 * zo, ipc2141(w, s)))
    best = min(table, key=lambda r: (abs(r["zdiff"] - 90) > 2, -r["s"], abs(r["zdiff"] - 90)))
    res = {"stackup": STACKUP_NAME, "layers": STACKUP, "h": H, "t": T, "er": ER, "mask": [MASK_T, MASK_ER],
           "check_single_0.37mm": round(z50, 1), "check_jlc_85ohm_case": round(2 * jlc85, 1),
           "table": table, "usb": {"w": best["w"], "s": best["s"], "zdiff": best["zdiff"]}}
    json.dump(res, open(OUT, "w"), indent=1)
    print("single-ended w 0.37: %.1f ohm; JLC 85-ohm case (w 0.2055 / s 0.1016): %.1f ohm" % (z50, 2 * jlc85))
    print("USB pair:", res["usb"])


if __name__ == "__main__":
    main()
